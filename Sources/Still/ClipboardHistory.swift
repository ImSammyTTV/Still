/// One remembered clipboard entry: text, an image (stored on disk) or a set of files.
struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    var id = UUID()
    var kind: Kind
    var text: String?
    var files: [String]?
    var imageFile: String?
    var width = 0, height = 0
    var date = Date()
    var source: String?

    /// What the menu shows for this entry.
    var title: String {
        switch kind {
        case .text:
            let line = (text ?? "").split(whereSeparator: \.isNewline).first.map(String.init) ?? ""
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            return trimmed.count > 60 ? String(trimmed.prefix(57)) + "…" : (trimmed.isEmpty ? "(blank text)" : trimmed)
        case .image: return "Image \(width) × \(height)"
        case .files:
            let names = (files ?? []).map { URL(fileURLWithPath: $0).lastPathComponent }
            return names.count > 1 ? "\(names[0]) + \(names.count-1) more" : (names.first ?? "Files")
        }
    }
    /// Identity used to merge duplicates (copying the same thing again moves it to the top).
    var signature: String {
        switch kind {
        case .text: return "t:" + (text ?? "")
        case .image: return "i:" + (imageFile ?? "")
        case .files: return "f:" + (files ?? []).joined(separator: "\n")
        }
    }
}

/// Small menu icons for image entries. Decoding a full PNG costs tens of milliseconds and the menu holds up to 100
/// rows, so icons are made once and kept; cost is small because each one is at most 56 px.
final class ClipboardThumbnails: @unchecked Sendable {
    private let cache = NSCache<NSString, NSImage>()
    func cached(_ url: URL) -> NSImage? { cache.object(forKey: url.lastPathComponent as NSString) }
    func image(for url: URL) -> NSImage? {
        if let cached = cached(url) { return cached }
        guard let thumbnail = ImageRenderer.thumbnail(url, maxPixelSize: 56) else { return nil }
        let width = CGFloat(thumbnail.width), height = CGFloat(thumbnail.height)
        let size = width >= height ? NSSize(width: 28, height: 28*height/max(1, width)) : NSSize(width: 28*width/max(1, height), height: 28)
        let image = NSImage(cgImage: thumbnail, size: size)
        cache.setObject(image, forKey: url.lastPathComponent as NSString)
        return image
    }
    func removeAll() { cache.removeAllObjects() }
    /// Fills the cache in the background so the first menu open doesn't have to.
    func prepare(_ urls: [URL]) {
        guard !urls.isEmpty else { return }
        Task.detached(priority: .utility) { [self] in for url in urls where cached(url) == nil { _ = image(for: url) } }
    }
}

/// Keeps a history of what you copy, like a clipboard manager, and puts any entry back on demand.
@MainActor final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    @AppStorage("clipboardEnabled") var enabled = true { didSet { enabled ? start() : stop() } }
    @AppStorage("clipboardLimit") var limit = 100 { didSet { trim(); save() } }
    @AppStorage("clipboardPasteAutomatically") var pasteAutomatically = false
    @Published private(set) var items: [ClipItem] = []

    private let pasteboard = NSPasteboard.general
    private var lastChange = 0
    private var timer: Timer?
    private var lastRead: Task<Void, Never>?
    private let thumbnails = ClipboardThumbnails()
    private let folder = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Still/Clipboard", isDirectory: true)
    private var indexURL: URL { folder.appendingPathComponent("history.json") }
    private var imageFolder: URL { folder.appendingPathComponent("images", isDirectory: true) }
    /// Marked by password managers and similar apps as "don't remember this".
    private static let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"]
    private static let maxImageBytes = 10 * 1024 * 1024
    private static let maxTextLength = 1_000_000

    private init() {
        try? FileManager.default.createDirectory(at: imageFolder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try? FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: folder.path)
        if let data = try? Data(contentsOf: indexURL) {
            if let saved = try? JSONDecoder().decode([ClipItem].self, from: data) { items = saved }
            // Keep a damaged history aside rather than overwrite it with the next copy.
            else { try? FileManager.default.moveItem(at: indexURL, to: folder.appendingPathComponent("history-damaged-\(Int(Date().timeIntervalSince1970)).json")) }
        }
        lastChange = pasteboard.changeCount
    }

    func start() {
        guard enabled, timer == nil else { return }
        lastChange = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in Task { @MainActor in self?.poll() } }
        thumbnails.prepare(items.compactMap(imageURL))
    }
    func stop() { timer?.invalidate(); timer = nil }

    private func poll() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard let reading = read() else { return }
        // In copy order, even when a text copy lands just after an image that is still being converted.
        let previous = lastRead
        lastRead = Task { await previous?.value; if let item = await reading.value { remember(item) } }
    }

    /// Reads the current clipboard into an entry, or nil when it's empty or marked private. The pasteboard is read
    /// here; converting an image is slow (Still's own captures land here too), so that part runs off the main thread.
    private func read() -> Task<ClipItem?, Never>? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: Self.privateTypes) else { return nil }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let item = ClipItem(kind: .files, files: urls.map(\.path), source: source)
            return Task { item }
        }
        if let text = pasteboard.string(forType: .string), !text.isEmpty, text.count <= Self.maxTextLength {
            let item = ClipItem(kind: .text, text: text, source: source)
            return Task { item }
        }
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), data.count <= Self.maxImageBytes {
            let imageFolder = imageFolder, thumbnails = thumbnails
            return Task.detached(priority: .userInitiated) {
                guard let image = NSBitmapImageRep(data: data), let png = image.representation(using: .png, properties: [:]) else { return nil }
                let name = SHA256.hash(data: png).prefix(12).map { String(format: "%02x", $0) }.joined() + ".png"
                let url = imageFolder.appendingPathComponent(name)
                if !FileManager.default.fileExists(atPath: url.path) { try? png.write(to: url) }
                _ = thumbnails.image(for: url)
                return ClipItem(kind: .image, imageFile: name, width: image.pixelsWide, height: image.pixelsHigh, source: source)
            }
        }
        return nil
    }

    func remember(_ item: ClipItem) {
        items.removeAll { $0.signature == item.signature }
        items.insert(item, at: 0)
        trim(); save()
    }

    /// Puts an entry back on the clipboard (and at the top of the history).
    func restore(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text: pasteboard.setString(item.text ?? "", forType: .string)
        case .files: pasteboard.writeObjects((item.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image: if let file = item.imageFile, let image = NSImage(contentsOf: imageFolder.appendingPathComponent(file)) { pasteboard.writeObjects([image]) }
        }
        lastChange = pasteboard.changeCount
        var moved = item; moved.date = Date(); remember(moved)
    }

    /// Restores an entry, then pastes it into the app you were using when that's switched on.
    func choose(_ item: ClipItem, returnTo app: NSRunningApplication?) {
        restore(item)
        guard pasteAutomatically else { return }
        guard AXIsProcessTrusted() else {
            _ = AXIsProcessTrustedWithOptions([kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary)
            return
        }
        app?.activate()
        DispatchQueue.main.asyncAfter(deadline: .now()+0.15) {
            let source = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: down) // V
                event?.flags = .maskCommand; event?.post(tap: .cghidEventTap)
            }
        }
    }

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id }; cleanImages(); save() }
    func clear() { items = []; cleanImages(); save() }
    private func imageURL(_ item: ClipItem) -> URL? { item.kind == .image ? item.imageFile.map { imageFolder.appendingPathComponent($0) } : nil }
    func thumbnail(_ item: ClipItem) -> NSImage? { imageURL(item).flatMap { thumbnails.image(for: $0) } }

    private func trim() { if items.count > limit { items.removeLast(items.count - limit); cleanImages() } }
    private func cleanImages() {
        let keep = Set(items.compactMap(\.imageFile))
        for file in (try? FileManager.default.contentsOfDirectory(atPath: imageFolder.path)) ?? [] where !keep.contains(file) {
            try? FileManager.default.removeItem(at: imageFolder.appendingPathComponent(file))
        }
    }
    private func save() { if let data = try? JSONEncoder().encode(items) { try? data.write(to: indexURL, options: .atomic) } }

    /// Builds menu items for the history: the first ten get 1–9 and 0 as keys.
    func menuItems(target: AnyObject, action: Selector, numbered: Bool) -> [NSMenuItem] {
        guard !items.isEmpty else {
            let empty = NSMenuItem(title: enabled ? "Nothing copied yet" : "Clipboard history is off", action: nil, keyEquivalent: ""); empty.isEnabled = false
            return [empty]
        }
        return items.enumerated().map { index, item in
            let key = numbered && index < 10 ? String((index+1) % 10) : ""
            let entry = NSMenuItem(title: item.title, action: action, keyEquivalent: key)
            entry.keyEquivalentModifierMask = []; entry.target = target; entry.representedObject = item.id
            entry.image = thumbnail(item) ?? NSImage(systemSymbolName: item.kind == .files ? "doc" : "text.alignleft", accessibilityDescription: nil)
            AppController.keepImageVisible(entry)
            if let source = item.source { entry.toolTip = "Copied from \(source)" }
            return entry
        }
    }
}
