// Builds web/vendor/icons.js: only the Lucide icons Still's pages use, so no window has to load and parse the whole
// set (some 2,000 icons) to draw a few dozen. Run it after using an icon the pages didn't use before:
//   node scripts/build-icons.mjs
// It keeps every Lucide name found as a quoted word or a data-lucide attribute in the pages and their scripts, which
// covers names picked at run time ('play' : 'pause'); test/icons.test.js fails if one is missing.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const here = path.dirname(new URL(import.meta.url).pathname), web = path.join(here, '..', 'web');
const lucide = createRequire(import.meta.url)(path.join(here, 'lucide.min.js'));
const pascal = (name) => name.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('');
const files = [...fs.readdirSync(web).filter((f) => /\.(html|js)$/.test(f)).map((f) => path.join(web, f)),
  ...fs.readdirSync(path.join(web, 'shared')).filter((f) => f.endsWith('.js')).map((f) => path.join(web, 'shared', f))];
const names = new Set();
for (const file of files) {
  const text = fs.readFileSync(file, 'utf8');
  for (const m of text.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) if (lucide.icons[pascal(m[1])]) names.add(m[1]);
}
const icons = Object.fromEntries([...names].sort().map((n) => [n, lucide.icons[pascal(n)]]));
const out = `/**
 * Lucide icons used by Still, from lucide ${lucide.version || '1.61.0'} (ISC license, https://lucide.dev).
 * Generated by scripts/build-icons.mjs; don't edit by hand.
 */
(function (root) {
  const icons = ${JSON.stringify(icons)};
  const base = { xmlns: 'http://www.w3.org/2000/svg', width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' };
  const NS = 'http://www.w3.org/2000/svg';
  function draw(name, attrs) {
    const svg = document.createElementNS(NS, 'svg');
    for (const [k, v] of Object.entries({ ...base, ...attrs })) svg.setAttribute(k, String(v));
    for (const [tag, a] of icons[name]) { const part = document.createElementNS(NS, tag); for (const [k, v] of Object.entries(a)) part.setAttribute(k, String(v)); svg.append(part); }
    return svg;
  }
  // Swaps each <i data-lucide="name"> for its drawing, keeping the element's own attributes, as Lucide does.
  function createIcons({ attrs = {}, root: scope = document } = {}) {
    for (const el of scope.querySelectorAll('[data-lucide]')) {
      const name = el.getAttribute('data-lucide');
      if (el instanceof SVGElement || !icons[name]) continue;
      const own = {};
      for (const a of el.attributes) if (a.name !== 'data-lucide') own[a.name] = a.value;
      const svg = draw(name, { ...attrs, ...own, class: ['lucide', \`lucide-\${name}\`, own.class].filter(Boolean).join(' ') });
      el.replaceWith(svg);
    }
  }
  root.lucide = { icons, createIcons };
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(web, 'vendor', 'icons.js'), out);
console.log(`${names.size} icons, ${(out.length / 1024).toFixed(1)} KB`);
